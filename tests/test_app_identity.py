"""Store apps and installed web apps (PWAs): catalog, launch, window matching, close."""

import pytest

from servo.perception import app_identity as ai
from servo.perception.app_identity import StartApp

FB_STORE = "FACEBOOK.FACEBOOK_8xx8rvfyw5nnt!App"
FB_PWA = "www.facebook.com-1C2D851A_n468xs7erp6tc!App"
WHATSAPP = "5319275A.WhatsAppDesktop_cv1g1gvanyjgm!App"
DIA = "TheBrowserCompany.Dia_ttt1ap7aakyb4!Dia"
NOTEPAD = "Microsoft.WindowsNotepad_8wekyb3d8bbwe!App"

APPS = [StartApp("Facebook", FB_PWA), StartApp("Facebook", FB_STORE), StartApp("WhatsApp", WHATSAPP),
        StartApp("Microsoft Teams", "MSTeams_8wekyb3d8bbwe!MSTeams"), StartApp("Dia", DIA),
        StartApp("YouTube", "msedge._crx_agimnkijcaahngcdmfeangaknmldooml"),
        StartApp("Notepad", NOTEPAD),
        StartApp("Office junk", "yh1BV5!!!!4!!!!MKKSkWxpFiles<")]


@pytest.fixture
def start_menu(monkeypatch):
    import servo.cognition.windows_context as wc
    monkeypatch.setattr(ai, "start_apps", lambda refresh=False: list(APPS))
    engine = wc.WindowsContextEngine()
    monkeypatch.setattr(wc, "windows_context", engine)
    return engine


@pytest.mark.parametrize("app_id,kind", [
    (FB_PWA, "web_app"), ("msedge._crx_abc", "web_app"), ("Chrome._crx_abc", "web_app"),
    (FB_STORE, "store"), (WHATSAPP, "store"), ("Chrome", "desktop"), ("Microsoft.AutoGenerated.{A5}", "desktop"),
])
def test_classify(app_id, kind):
    assert ai.classify(app_id) == kind


def test_unsafe_app_ids_are_refused():
    assert ai.safe_app_id(WHATSAPP)
    for bad in ["yh1BV5!!!!4!!!!MKKSkWxpFiles<", "x & calc", "..\\..\\evil", 'a"b']:
        assert not ai.safe_app_id(bad), bad
    with pytest.raises(ValueError):
        ai.launch("x & calc")


def test_catalog_knows_store_and_web_apps(start_menu):
    ok, info = start_menu.is_installed("whatsapp")
    assert ok and info.kind == "store" and info.app_ids == [WHATSAPP]
    ok, fb = start_menu.is_installed("facebook")
    assert ok and fb.app_ids == [FB_PWA, FB_STORE]          # both Facebook entries
    assert start_menu.is_installed("teams")[0]               # "Microsoft " prefix dropped
    assert start_menu.is_installed("youtube")[1].kind == "web_app"
    assert not start_menu.is_installed("office junk")[0]     # unsafe id never catalogued


def test_known_desktop_app_keeps_exe_but_learns_its_app_id(start_menu):
    ok, info = start_menu.is_installed("notepad")
    assert info.executable.lower().endswith("notepad.exe") and info.app_ids == [NOTEPAD]


def test_context_names_the_app_not_filler_words(start_menu):
    names = [a.name for a in start_menu.retrieve_context("send hi to mom on whatsapp").matched_installed_apps]
    assert names[:1] == ["WhatsApp"]
    text = start_menu.retrieve_context("open whatsapp").to_prompt_text()
    assert "Store app; open it with: launch WhatsApp" in text


# ------------------------------------------------------------- window matching

def _win(hwnd, proc, title, app_id):
    return {"hwnd": hwnd, "process": proc, "title": title, "app_id": app_id}


def test_web_app_window_is_never_the_browser(start_menu):
    from servo.daemon import copilot
    fb = _win(5, "msedge.exe", "Facebook - Messenger | Facebook", FB_STORE)
    edge = _win(6, "msedge.exe", "New tab - Microsoft​ Edge", "")
    assert not copilot._matches_app(dict(fb), "edge", "msedge.exe")
    assert copilot._matches_app(dict(edge), "edge", "msedge.exe")
    assert copilot._matches_app(dict(fb), "facebook", "facebook.exe", (FB_PWA, FB_STORE))
    # A browser's own window is not a web app (Dia carries its package id).
    assert not ai.is_web_app_window(7, "dia.exe", DIA)
    assert ai.is_web_app_window(5, "msedge.exe", FB_STORE)
    assert ai.is_web_app_window(5, "chrome.exe", "Chrome._crx_xyz")
    assert not ai.is_web_app_window(6, "msedge.exe", "MSEdge")  # unlisted id: the browser


def test_find_and_launch_by_app_id(monkeypatch, start_menu):
    from servo.daemon import copilot
    import servo.actuation.sandboxing as sb
    shown = [_win(5, "msedge.exe", "Facebook", FB_STORE), _win(8, "dia.exe", "Profile 1: Facebook", DIA)]
    monkeypatch.setattr(copilot.windows, "list_windows", lambda: [dict(w) for w in shown])
    assert copilot.find_app_window("facebook") == 5
    assert copilot.find_app_window("edge") is None

    launched = []

    def fake_launch(aid):
        launched.append(aid)
        shown.append(_win(9, "whatsapp.root.exe", "WhatsApp", WHATSAPP))

    monkeypatch.setattr(ai, "launch", fake_launch)
    monkeypatch.setattr(sb, "activate_window", lambda h: True)
    monkeypatch.setattr(copilot.time, "sleep", lambda s: None)
    hwnd, title = copilot.launch_or_focus_app("whatsapp")
    assert launched == [WHATSAPP] and (hwnd, title) == (9, "WhatsApp")


def test_window_label_for_the_planner(monkeypatch):
    monkeypatch.setattr(ai, "start_apps", lambda refresh=False: list(APPS))
    assert ai.window_label(5, "msedge.exe", FB_STORE) == "Facebook — installed web app (runs in msedge.exe)"
    assert ai.window_label(9, "whatsapp.root.exe", WHATSAPP) == "WhatsApp — Store app (whatsapp.root.exe)"
    assert ai.window_label(8, "dia.exe", DIA) == "dia.exe"


# ------------------------------------------------------------- close

def test_close_counts_a_hidden_window_as_closed(monkeypatch):
    """WhatsApp/Teams hide to the tray on close instead of destroying the window."""
    import win32gui
    from servo.cognition.needle import _step
    from servo.control import handoff
    from servo.daemon import copilot
    from servo.planner.tool_calling import MacroPlan
    monkeypatch.setattr(copilot, "find_app_window", lambda n: 9)
    monkeypatch.setattr(handoff.windows, "is_window", lambda h: True)
    monkeypatch.setattr(handoff.windows, "get_window_title", lambda h: "WhatsApp")
    visible = iter([True] + [False] * 200)
    monkeypatch.setattr(handoff.windows, "is_visible", lambda h: next(visible))
    monkeypatch.setattr(win32gui, "PostMessage", lambda *a: None)
    coord = handoff.SystemHandoffCoordinator(target_hwnd=None, exclude_hwnds=lambda: set())
    plan = MacroPlan(goal="g", steps=[_step(1, "close_window", {"app_name": "whatsapp"}, "close")])
    rep = coord.execute_plan(plan).step_reports[0]
    assert rep.success and rep.verification == "confirmed"


# ------------------------------------------------------------- Chromium page accessibility

def test_sensor_asks_chromium_for_the_page_once(monkeypatch):
    from servo.perception import uia_sensor
    from servo.perception.scene_index import SceneElement, SceneIndex

    def scene(n, doc=False):
        els = {i: SceneElement(element_id=i, role="Document" if doc and i == 0 else "Button", label=f"b{i}",
                               bbox_screen=(0, 0, 1, 1), bbox_norm=(0, 0, 1, 1), center_screen=(0, 0))
               for i in range(n)}
        return SceneIndex(hwnd=42, window_title="Facebook", source="uia", elements=els)

    results = iter([scene(7), scene(90, doc=True)])
    asked = []
    monkeypatch.setattr(uia_sensor.UIASensor, "_sense_once", lambda self: next(results))
    monkeypatch.setattr(uia_sensor, "_is_chromium_host", lambda h: True)
    monkeypatch.setattr(uia_sensor, "_request_accessibility", lambda h: asked.append(h) or True)
    monkeypatch.setattr(uia_sensor.time, "sleep", lambda s: None)
    uia_sensor._nudged.discard(42)
    sensor = uia_sensor.UIASensor.__new__(uia_sensor.UIASensor)
    sensor.hwnd = 42
    assert len(sensor.sense().elements) == 90 and asked == [42]
    # Never asks twice for the same window (a genuinely small page stays cheap).
    monkeypatch.setattr(uia_sensor.UIASensor, "_sense_once", lambda self: scene(7))
    sensor.sense()
    assert asked == [42]
